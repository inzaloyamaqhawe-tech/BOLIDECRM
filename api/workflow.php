<?php
declare(strict_types=1);

function workflow_date(mixed $value): bool {
    return is_string($value) && preg_match('/^\d{4}-\d{2}-\d{2}$/D', $value) === 1
        && (DateTimeImmutable::createFromFormat('!Y-m-d', $value) ?: null)?->format('Y-m-d') === $value;
}
function workflow_diff(mixed $before, mixed $after, string $path = ''): array {
    if ($before === $after || ((is_int($before)||is_float($before)) && (is_int($after)||is_float($after)) && $before==$after)) return [];
    if ((is_array($before) && !array_is_list($before)) || (is_array($after) && !array_is_list($after))) {
        $changes=[];
        foreach(array_unique(array_merge(array_keys(is_array($before)?$before:[]),array_keys(is_array($after)?$after:[]))) as $key) {
            $changes=array_merge($changes,workflow_diff($before[$key]??null,$after[$key]??null,$path===''?(string)$key:$path.'.'.$key));
        }
        return $changes;
    }
    return [['field'=>$path,'before'=>$before,'after'=>$after]];
}
function workflow_validate(array $deal, ?array $before, array $attachments, array $users): void {
    $w=$deal['workflow']??[]; $stage=$deal['stage']??'lead';
    $today=(new DateTimeImmutable('now',new DateTimeZone('Africa/Johannesburg')))->format('Y-m-d');
    $userIds=array_column($users,'id');
    $files=array_filter($attachments,fn($a)=>($a['dealId']??'')===$deal['id']);
    $fileIds=array_column($files,'id');
    if($stage==='won' && (!workflow_date($w['signedOn']??null) || $w['signedOn']>$today || !in_array($w['signedAttachmentId']??'',$fileIds,true))) throw new InvalidArgumentException('Won requires a signature date (today or earlier) and the signed final proposal attachment.');
    if(in_array($stage,['quote','final_proposal','negotiation','won'],true) && (!$before || ($before['stage']??'')!==$stage)) {
        $items=$w['kyc']??[];
        foreach(['registration','identity','address'] as $id) if(!array_filter($items,fn($i)=>($i['id']??'')===$id&&!empty($i['required']))) throw new InvalidArgumentException('Complete the standard KYC checklist before progressing.');
        foreach($items as $item) if(!empty($item['required'])) {
            if(($item['status']??'')!=='verified'||empty($item['verifiedAt'])||!in_array($item['verifiedBy']??'',$userIds,true)||!in_array($item['attachmentId']??'',$fileIds,true)||(!empty($item['expiresOn'])&&(!workflow_date($item['expiresOn'])||$item['expiresOn']<$today))) throw new InvalidArgumentException('Verify all required KYC documents and check their expiry before progressing.');
        }
    }
    if(!empty($w['proposalDueOverride'])&&!workflow_date($w['proposalDueOverride']))throw new InvalidArgumentException('Invalid proposal deadline.');
    if(!empty($w['escalationUserId'])&&!in_array($w['escalationUserId'],$userIds,true))throw new InvalidArgumentException('Invalid escalation person.');
    if($before && (($before['workflow']['proposalDueOverride']??null)!==($w['proposalDueOverride']??null) || substr($before['receivedAt']??'',0,10)!==substr($deal['receivedAt']??'',0,10)) && !trim($w['deadlineReason']??'')) throw new InvalidArgumentException('Explain the proposal deadline / received-date change.');
    if(!empty($w['proposalDueOverride'])&&!trim($w['deadlineReason']??''))throw new InvalidArgumentException('A deadline override needs an explanation.');
}

/** Called inside the revision-locked transaction. Existing unchanged imported deals
 * are not retroactively rejected; every changed active deal must meet the rules. */
function workflow_prepare(array &$snapshot,array $old,array $actor): void {
    $oldDeals=array_column($old['deals'],null,'id');
    $oldActivities=array_column($old['activities'],null,'id');
    $oldUsers=array_column($old['users'],null,'id');
    $dealIds=array_column($snapshot['deals'],'id');
    $activities=[];
    foreach($snapshot['activities'] as $a) {
        if(!empty($a['changes']))continue; // Audit events are generated by the server.
        if(isset($oldActivities[$a['id']]))$a=$oldActivities[$a['id']];
        else {$a['userId']=$actor['id'];$a['createdAt']=gmdate('Y-m-d\TH:i:s\Z');}
        $activities[$a['id']]=$a;
    }
    // Retain historical audit events even when a browser submits an older copy.
    foreach($old['activities'] as $a)if(!empty($a['changes'])&&in_array($a['dealId']??'',$dealIds,true))$activities[$a['id']]=$a;
    foreach($snapshot['deals'] as &$deal) {
        $before=$oldDeals[$deal['id']]??null;
        $actions=['lead'=>'Qualify/KYC Onboarding','qualified'=>'Preliminary Proposal','quote'=>'Final Proposal','final_proposal'=>'Negotiation','negotiation'=>'Final Proposal Signed'];
        unset($deal['workflow']['nextAction']);
        if(isset($actions[$deal['stage']]))$deal['workflow']['nextAction']=['title'=>$actions[$deal['stage']]];
        $fileIds=array_column(array_filter($snapshot['attachments'],fn($f)=>($f['dealId']??'')===$deal['id']),'id');
        foreach(array_merge([$deal['workflow']['signedAttachmentId']??null],array_column($deal['workflow']['kyc']??[],'attachmentId')) as $fileId) if($fileId&&!in_array($fileId,$fileIds,true))throw new InvalidArgumentException('A selected signature / KYC document cannot be deleted. Update the deal selections first.');
        if(isset($deal['workflow']['kyc']))foreach($deal['workflow']['kyc'] as &$item) {
            $previous=current(array_filter($before['workflow']['kyc']??[],fn($i)=>($i['id']??'')===($item['id']??'')));
            if(($item['status']??'')==='verified' && (!$previous||($previous['status']??'')!=='verified'||($previous['attachmentId']??null)!==($item['attachmentId']??null)||($previous['expiresOn']??null)!==($item['expiresOn']??null))) {$item['verifiedBy']=$actor['id'];$item['verifiedAt']=gmdate('Y-m-d\TH:i:s\Z');}
            elseif(($item['status']??'')==='verified'&&$previous){$item['verifiedBy']=$previous['verifiedBy']??null;$item['verifiedAt']=$previous['verifiedAt']??null;}
            else {unset($item['verifiedBy'],$item['verifiedAt']);}
        }
        unset($item);
        $a=$before??[];$b=$deal;
        foreach(['id','createdAt','updatedAt','stageChangedAt'] as $key){unset($a[$key],$b[$key]);}
        $changes=workflow_diff($a,$b);
        if(!$changes)continue;
        workflow_validate($deal,$before,$snapshot['attachments'],$snapshot['users']);
        $deal['updatedAt']=gmdate('Y-m-d\TH:i:s\Z');
        $deal['createdAt']=$before['createdAt']??$deal['updatedAt'];
        $deal['stageChangedAt']=(!$before||$before['stage']!==$deal['stage'])?$deal['updatedAt']:($before['stageChangedAt']??$deal['createdAt']);
        if(empty($deal['proposalSentAt'])&&in_array($deal['stage'],['quote','final_proposal','negotiation','won'],true))$deal['proposalSentAt']=$deal['updatedAt'];
        $id='audit-'.bin2hex(random_bytes(16));
        $activities[$id]=['id'=>$id,'dealId'=>$deal['id'],'type'=>'update','body'=>$before?'Deal fields changed':'Deal created','userId'=>$actor['id'],'createdAt'=>$deal['updatedAt'],'changes'=>$changes];
    }
    unset($deal);
    $snapshot['activities']=array_values($activities);
    foreach($snapshot['tasks'] as $task) {
        $before=current(array_filter($old['tasks'],fn($t)=>$t['id']===$task['id']));
        if($before===$task)continue;
        if(!trim($task['title']??'')||!in_array($task['assigneeId']??'',array_column($snapshot['users'],'id'),true))throw new InvalidArgumentException('Tasks require a title and valid assignee.');
        if(!in_array($task['priority']??'normal',['low','normal','high'],true)||!in_array($task['recurrence']??'none',['none','daily','weekly','monthly'],true))throw new InvalidArgumentException('Invalid task priority or recurrence.');
        if(!empty($task['dueDate'])&&!workflow_date($task['dueDate']))throw new InvalidArgumentException('Invalid task due date.');
        if(($task['recurrence']??'none')!=='none'&&!workflow_date($task['dueDate']??null))throw new InvalidArgumentException('Recurring tasks need a due date.');
        if(!empty($task['reminderAt'])&&strtotime($task['reminderAt'])===false)throw new InvalidArgumentException('Invalid reminder time.');
    }
    foreach($snapshot['users'] as $u)if($u['id']!==$actor['id']&&($u['savedViews']??[])!==($oldUsers[$u['id']]['savedViews']??[]))throw new InvalidArgumentException('Saved views belong to the signed-in user.');
}
